"""Draw the Whisper Face app icon from the app's own face code.

The icon is the parrot close up: its crest and the top of its head on the
window's cream ground, eyes closed in a smile, cut off by the rounded square.
Nothing here is hand-drawn. The parrot is ``whisper_face_characters``' op
list, drawn through ``whisper_face_render.replay_ops`` for the Apple icon set
(the same path the window and the recording overlay use) and through
``whisper_face_characters._svg_op`` for the SVGs (the path the site and
``icons/faces/color`` use). The ground is the window's cream, the edge a
deeper shade of it.

Writes, from the current checkout:

* ``icons/WhisperFace.icns``: every size from 16 to 512 points at 1x and 2x,
  each drawn at its own pixel size, packed by ``iconutil``. The launcher app
  ships it, and the update alerts show it.
* ``icons/core.svg``: the same icon on the 1024 canvas, the README's image.
  Its ground and face are separate groups so it can be brought into Icon
  Composer as two layers.
* ``site/public/favicon.svg``: the rounded square alone, for a browser tab.

Usage (macOS, from the repository root)::

    uv run scripts/make_app_icon.py              # rewrite all three
    uv run scripts/make_app_icon.py --png DIR    # also keep the PNGs in DIR
    python3 scripts/make_app_icon.py --check     # fail if the SVGs drifted

``--check`` needs no AppKit: it rebuilds the two SVGs as text and compares.
The ``.icns`` is pixels from the system's rasterizer, which differs a little
between macOS releases, so it is regenerated on purpose rather than checked
byte for byte; ``tests/test_macos_distribution.py`` holds its sizes.
"""

from __future__ import annotations

import argparse
import math
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from whisper_face_characters import FRAMES, _svg_op, character_ops  # noqa: E402
from whisper_face_theme import LIGHT_PALETTE  # noqa: E402

ICNS = ROOT / "icons" / "WhisperFace.icns"
CORE_SVG = ROOT / "icons" / "core.svg"
FAVICON = ROOT / "site" / "public" / "favicon.svg"
BANNER = "<!-- Generated by scripts/make_app_icon.py. Do not edit. -->\n"

# The macOS icon grid: an 824-unit rounded square centred on a 1024 canvas,
# the 100 units round it left for the system's drop shadow.
CANVAS = 1024.0
PLATE = 824.0
PLATE_ORIGIN = (CANVAS - PLATE) / 2.0
# A superellipse of this exponent is close to Apple's continuous corner.
PLATE_EXPONENT = 5.0
PLATE_STEPS = 360

# The parrot: idle, eyes closed, no speech puffs, no hard shadow (the plate
# edge already cuts it). Its 256-unit design box is drawn 1100 units wide,
# centred low, so the crest stands at the top and the cheeks at the bottom.
FACE = "parrot"
FRAME = "idle"
BLINK = 1.0
FACE_SIDE = 1100.0
FACE_CENTRE = (512.0, 660.0)

GROUND = LIGHT_PALETTE.bg
# The edge: a deeper cream, the ground mixed a quarter of the way to the
# theme's outline ink, laid inside the plate under the parrot. On a white
# Finder window the cream square keeps its outline; on a dark one it is a
# shade of the cream it sits in. It is EDGE_WIDTH canvas units wide at the
# full size and never less than one device pixel at the small ones.
EDGE_MIX = 0.25
EDGE = tuple(ground + EDGE_MIX * (line - ground)
             for ground, line in zip(GROUND, LIGHT_PALETTE.line))
EDGE_WIDTH = 8.0
# The favicon is shown 16 to 32 pixels wide: one pixel at 32 is ~26 units.
FAVICON_EDGE_WIDTH = 26.0

# (file name in the .iconset, pixel side) for every size iconutil packs.
ICONSET = tuple(
    (f"icon_{points}x{points}{suffix}.png", points * scale)
    for points in (16, 32, 128, 256, 512)
    for suffix, scale in (("", 1), ("@2x", 2)))


def _hex(color) -> str:
    return "#%02x%02x%02x" % tuple(
        max(0, min(255, round(channel * 255))) for channel in color)


def _num(value: float) -> str:
    text = f"{value:.2f}".rstrip("0").rstrip(".")
    return "0" if text in ("-0", "") else text


def plate_points() -> list[tuple[float, float]]:
    """The rounded square's outline on the 1024 canvas, y down."""
    half = PLATE / 2.0
    centre = PLATE_ORIGIN + half
    power = 2.0 / PLATE_EXPONENT
    points = []
    for step in range(PLATE_STEPS):
        angle = 2.0 * math.pi * step / PLATE_STEPS
        c, s = math.cos(angle), math.sin(angle)
        points.append((
            round(centre + half * math.copysign(abs(c) ** power, c), 2),
            round(centre + half * math.copysign(abs(s) ** power, s), 2)))
    return points


def face_ops():
    mouth, level = FRAMES[FRAME]
    return character_ops(FACE, mouth, level, BLINK, (0.0, 0.0),
                         shadow=False, whispers=False)


def face_transform() -> tuple[float, float, float]:
    """(x, y, scale) taking the 256 design box onto the canvas."""
    scale = FACE_SIDE / 256.0
    return (FACE_CENTRE[0] - 128.0 * scale, FACE_CENTRE[1] - 128.0 * scale,
            scale)


def _svg(view_box: str, edge_width: float) -> str:
    plate = "M" + " L".join(f"{_num(x)} {_num(y)}" for x, y in plate_points())
    x, y, scale = face_transform()
    face = "".join(_svg_op(op) for op in face_ops())
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" '
        f'viewBox="{view_box}">\n{BANNER}'
        f'<defs><clipPath id="plate"><path d="{plate} Z"/></clipPath></defs>\n'
        '<g clip-path="url(#plate)">\n'
        f'<g id="ground"><rect x="0" y="0" width="1024" height="1024" '
        f'fill="{_hex(GROUND)}"/><path id="edge" d="{plate} Z" fill="none" '
        f'stroke="{_hex(EDGE)}" stroke-width="{_num(2.0 * edge_width)}"/></g>\n'
        f'<g id="face" transform="translate({_num(x)} {_num(y)}) '
        f'scale({scale:g})">{face}</g>\n'
        '</g>\n</svg>\n')


def core_svg() -> str:
    """The icon on the full macOS canvas, transparent round the plate."""
    return _svg("0 0 1024 1024", EDGE_WIDTH)


def favicon_svg() -> str:
    """The plate alone: a browser tab has no room for the shadow margin."""
    return _svg(f"{_num(PLATE_ORIGIN)} {_num(PLATE_ORIGIN)} "
                f"{_num(PLATE)} {_num(PLATE)}", FAVICON_EDGE_WIDTH)


def generated_svgs() -> dict[Path, str]:
    return {CORE_SVG: core_svg(), FAVICON: favicon_svg()}


# ---------------------------------------------------------------- AppKit --

def draw_icon(pixels: float, origin=(0.0, 0.0), height=None, *,
              edge: bool = True) -> None:
    """Draw the icon ``pixels`` wide into the current graphics context.

    ``origin`` is its top-left corner in a y-down frame ``height`` tall (the
    context's own height by default), so it can be placed on a sheet.
    """
    from AppKit import (
        NSAffineTransform, NSBezierPath, NSColor, NSGraphicsContext, NSShadow,
    )
    from whisper_face_render import replay_ops

    height = pixels if height is None else height
    k = pixels / CANVAS
    context = NSGraphicsContext.currentContext()
    context.saveGraphicsState()
    flip = NSAffineTransform.transform()
    flip.translateXBy_yBy_(origin[0], height - origin[1])
    flip.scaleXBy_yBy_(k, -k)
    flip.concat()

    plate = NSBezierPath.bezierPath()
    points = plate_points()
    plate.moveToPoint_(points[0])
    for point in points[1:]:
        plate.lineToPoint_(point)
    plate.closePath()

    # The drop shadow of Apple's icon template, under the plate.
    context.saveGraphicsState()
    shadow = NSShadow.alloc().init()
    shadow.setShadowOffset_((0.0, -10.0 * k))
    shadow.setShadowBlurRadius_(10.0 * k)
    shadow.setShadowColor_(
        NSColor.colorWithSRGBRed_green_blue_alpha_(0, 0, 0, 0.30))
    shadow.set()
    NSColor.colorWithSRGBRed_green_blue_alpha_(*GROUND, 1.0).set()
    plate.fill()
    context.restoreGraphicsState()

    context.saveGraphicsState()
    plate.addClip()
    if edge:
        # Half the stroke falls outside the clip, so it is drawn twice as
        # wide as it shows, and never thinner than one device pixel.
        NSColor.colorWithSRGBRed_green_blue_alpha_(*EDGE, 1.0).set()
        plate.setLineWidth_(2.0 * max(EDGE_WIDTH, 1.0 / k))
        plate.stroke()
    context.saveGraphicsState()
    x, y, scale = face_transform()
    place = NSAffineTransform.transform()
    place.translateXBy_yBy_(x, y)
    place.scaleBy_(scale)
    place.concat()
    replay_ops(face_ops())
    context.restoreGraphicsState()
    context.restoreGraphicsState()
    context.restoreGraphicsState()


def render_png(pixels: int, path: Path, **options) -> None:
    from AppKit import (
        NSBitmapImageFileTypePNG, NSBitmapImageRep, NSColorSpace,
        NSGraphicsContext,
    )

    rep = NSBitmapImageRep.alloc().initWithBitmapDataPlanes_pixelsWide_pixelsHigh_bitsPerSample_samplesPerPixel_hasAlpha_isPlanar_colorSpaceName_bytesPerRow_bitsPerPixel_(
        None, pixels, pixels, 8, 4, True, False, "NSDeviceRGBColorSpace",
        0, 32)
    rep = rep.bitmapImageRepByRetaggingWithColorSpace_(
        NSColorSpace.sRGBColorSpace())
    context = NSGraphicsContext.graphicsContextWithBitmapImageRep_(rep)
    NSGraphicsContext.saveGraphicsState()
    NSGraphicsContext.setCurrentContext_(context)
    try:
        context.setShouldAntialias_(True)
        draw_icon(float(pixels), **options)
        context.flushGraphics()
    finally:
        NSGraphicsContext.restoreGraphicsState()
    data = rep.representationUsingType_properties_(
        NSBitmapImageFileTypePNG, {})
    path.write_bytes(bytes(data))


def build_icns(destination: Path, keep: Path | None = None) -> None:
    iconutil = shutil.which("iconutil")
    if not iconutil:
        raise SystemExit("iconutil is required: run this on a Mac")
    with tempfile.TemporaryDirectory() as directory:
        iconset = Path(directory) / "WhisperFace.iconset"
        iconset.mkdir()
        for name, pixels in ICONSET:
            render_png(pixels, iconset / name)
        packed = Path(directory) / "WhisperFace.icns"
        subprocess.run([iconutil, "-c", "icns", "-o", str(packed),
                        str(iconset)], check=True)
        if keep is not None:
            keep.mkdir(parents=True, exist_ok=True)
            shutil.copytree(iconset, keep / iconset.name, dirs_exist_ok=True)
            render_png(1024, keep / "WhisperFace-1024.png")
        destination.write_bytes(packed.read_bytes())


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true",
                        help="fail if the committed SVGs have drifted")
    parser.add_argument("--png", type=Path,
                        help="also keep the iconset PNGs in this directory")
    args = parser.parse_args(argv)

    stale = []
    for path, text in generated_svgs().items():
        if args.check:
            current = path.read_text(encoding="utf-8") if path.exists() else ""
            if current != text:
                stale.append(path.relative_to(ROOT).as_posix())
        else:
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT)}")
    if args.check:
        if stale:
            print("stale, run scripts/make_app_icon.py: " + ", ".join(stale))
            return 1
        print("app icon SVGs match the spec")
        return 0
    build_icns(ICNS, args.png)
    print(f"wrote {ICNS.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
